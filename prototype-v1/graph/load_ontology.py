"""
load_ontology.py — load a domain's graph into Neo4j.

Loads both halves, in order:

  <key>_ontology_seed.cypher   the domain nodes and their RELATED_TO edges
  <key>_concept_seed.cypher    the mined concepts and their INDICATES edges

Both are generated by graph/mine_concept_markers.py from domains/<key>.json,
so neither is hand-edited and neither can drift from the pack.

Order matters less than it used to — the concept seed MERGEs the domain node
it attaches to rather than MATCHing it, so it can be loaded alone. It is
still loaded second, because the ontology seed is what carries the
descriptions and the RELATED_TO edges.

    export NEO4J_URI="neo4j+s://xxxx.databases.neo4j.io"
    export NEO4J_USER="neo4j"
    export NEO4J_PASSWORD="..."
    export NEO4J_DATABASE="neo4j"      # some Aura Free instances use the instance id

    python load_ontology.py --domain legal
    python load_ontology.py --domain medical

Verify afterwards with:

    python verify_ontology.py --domain legal
"""

import argparse
import os
import sys
from pathlib import Path

from neo4j import GraphDatabase

HERE = Path(__file__).resolve().parent


def statements(script: str):
    """Split on ';', dropping comment-only lines so they don't become queries."""
    for block in script.split(";"):
        cleaned = "\n".join(
            line for line in block.splitlines()
            if not line.strip().startswith("//")
        ).strip()
        if cleaned:
            yield cleaned


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--domain", default="legal", help="which domain pack's graph to load")
    ap.add_argument("--uri", default=None)
    ap.add_argument("--dry-run", action="store_true",
                    help="count the statements without connecting to anything")
    args = ap.parse_args()

    required = [
        HERE / f"{args.domain}_ontology_seed.cypher",
        HERE / f"{args.domain}_concept_seed.cypher",
    ]
    # NARROWS and CO_OCCURS between concepts (graph/mine_graph_depth.py).
    # Genuinely optional: a domain whose depth has not been mined yet still
    # has a complete, working graph, so its absence is reported and skipped
    # rather than treated as a broken install.
    depth = HERE / f"{args.domain}_depth_seed.cypher"
    files = required + ([depth] if depth.exists() else [])
    if not depth.exists():
        print(f"note: {depth.name} not present — loading without concept-level "
              f"depth (run mine_graph_depth.py --domain {args.domain} to add it)")

    missing = [f for f in required if not f.exists()]
    if missing:
        available = sorted({p.name.split("_")[0] for p in HERE.glob("*_ontology_seed.cypher")})
        sys.exit(
            f"Missing: {', '.join(f.name for f in missing)}\n"
            f"Generate them with:  python mine_concept_markers.py --domain {args.domain}\n"
            f"Domains with seeds already: {', '.join(available) or 'none'}"
        )

    if args.dry_run:
        for f in files:
            print(f"{f.name}: {sum(1 for _ in statements(f.read_text()))} statements")
        return

    uri = args.uri or os.environ.get("NEO4J_URI", "bolt://localhost:7687")
    user = os.environ.get("NEO4J_USER", "neo4j")
    password = os.environ.get("NEO4J_PASSWORD", "password")
    database = os.environ.get("NEO4J_DATABASE", "neo4j")

    total = 0
    with GraphDatabase.driver(uri, auth=(user, password)) as driver:
        with driver.session(database=database) as session:
            for f in files:
                count = 0
                for statement in statements(f.read_text()):
                    session.run(statement)
                    count += 1
                print(f"  {f.name}: {count} statements")
                total += count

    print(f"\nLoaded {total} statements for domain '{args.domain}' into {uri} "
          f"(database={database}).")
    print(f"Verify with:  python verify_ontology.py --domain {args.domain}")


if __name__ == "__main__":
    main()
